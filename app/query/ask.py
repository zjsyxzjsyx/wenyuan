"""The query chains: `search` (understand -> retrieve -> small-to-big sources) and `ask` (search + cited answer).

`python -m app.query.ask "How do I delete everything in Redis?" --library redis`
Every stage is a span under one trace, so a slow or wrong answer can be traced to
the stage that caused it. `on_event(name, data)` reports each stage as it finishes;
the HTTP API turns these into server-sent events so the client sees progress
(understanding, sources) seconds before the answer.

With `owner_id`, the caller's private notes are searched along with the public
libraries. Routing rule: if any private note reaches the answer's context, the
answer is generated by `local_llm` (the local model), never by a remote API.
"""
from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from dataclasses import asdict, dataclass, field

from sqlalchemy.orm import Session as DBSession

from app.db.models import engine
from app.generation.answer import REFUSAL, Answer, answer, apply_verification
from app.generation.verify import verify
from app.ingest.summarize import COLLECTION as SUMMARIES
from app.ingest.sites import SITES
from app.models.llm import LLM
from app.models.local import ModelServer
from app.query import multihop
from app.query.understand import Understanding, understand
from app.retrieval import milvus_store
from app.retrieval.context import Source, build_sources, parent_blocks
from app.retrieval.fusion import best_per_block, rrf
from app.retrieval.rerank import rerank
from app.tokenizer import TiktokenTokenizer
from app.tracing import spans

COLLECTION = "chunks_v2"   # v0.7 experiments ran on "chunks_struct_merge"
OnEvent = Callable[[str, dict], None]


@dataclass
class AskConfig:
    collection: str = COLLECTION
    # Defaults are the best measured setting (W2, 1184 SO questions): hybrid search with the
    # LLM's candidate API names on the BM25 side. Reranking on top of that was significantly
    # worse (Recall@5 -2.4, +440 ms): the reranker prefers terse API reference pages.
    mode: str = "hybrid"         # dense | hybrid
    top_k: int = 50
    rerank_top: int = 0          # rerank the first N hits; 0: off
    summaries: bool = False      # also search section summaries/questions (E5)
    budget: int = 6000           # context tokens for the answer
    # Claim-level citation check after generation (E8, 99 SO questions, DeepSeek as judge): answers
    # with an unsupported claim 47.8% -> 23.0% (significant), fully correct answers unchanged,
    # 5 more refusals (none of them correct before), about +0.85 s per answer.
    verify: bool = True
    # Multi-hop (E9): split a question that needs several lookups into sub-queries, searched in turn
    # and interleaved. Cross-library questions: both pages in the top 10, 0.30 -> 0.45 (significant);
    # single-hop SO questions unchanged (gate passed), as one sub-query keeps the first search. "" = off.
    multihop: str = "decompose"


@dataclass
class SearchResult:
    understanding: Understanding
    sources: list[Source] = field(default_factory=list)
    retrieved: list[dict] = field(default_factory=list)   # {"url", "heading_path", "score"} in final order
    trace_id: str = ""


@dataclass
class AskResult:
    answer: Answer
    understanding: Understanding | None
    trace_id: str = ""
    retrieved: list[dict] = field(default_factory=list)
    sources: list[Source] = field(default_factory=list)


def is_private(s: Source) -> bool:
    return s.url.startswith("private://")


def source_view(s: Source) -> dict:
    """What a client sees of a source (the full text stays server-side for `ask`)."""
    return {"sid": s.sid, "url": s.url, "title": s.title, "heading_path": s.heading_path, "tokens": s.tokens,
            "private": is_private(s), "section_id": s.section_id}


def _noop(name: str, data: dict) -> None:
    pass


def offered(libraries: list[str] | None) -> list[str]:
    """Libraries the router may choose among: the caller's (possibly none), or all when unrestricted."""
    return sorted(SITES) if libraries is None else list(libraries)


def narrowed(routed: list[str], libraries: list[str] | None) -> list[str] | None:
    """The search scope: the router may narrow `libraries`, never widen them. From the API they are
    the caller's courses, and a model's guess must not send a question into someone else's course.
    An empty routing answer means "could be any" of those offered; None (eval, CLI) means all."""
    chosen = [lib for lib in routed if libraries is None or lib in libraries]
    return chosen or libraries


def _retrieve(u: Understanding, libraries: list[str] | None, cfg: AskConfig, models: ModelServer,
              tokenizer: TiktokenTokenizer, owner_id: int | None,
              llm: LLM | None = None) -> tuple[list[dict], list[Source]]:
    scope = narrowed(u.libraries, libraries)
    with spans.span("retrieval", f"{cfg.mode}_search", libraries=scope) as s:
        # The standalone question keeps the learner's details (error text, code) and has its
        # references resolved; exact names go to BM25 through bm25_text().
        vector = models.embed([u.standalone_question])[0]
        mc = milvus_store.client()
        if cfg.mode == "hybrid":
            hits = milvus_store.hybrid_search(mc, cfg.collection, vector, u.bm25_text(), top_k=cfg.top_k,
                                              libraries=scope, owner_id=owner_id)
        else:
            hits = milvus_store.dense_search(mc, cfg.collection, vector, top_k=cfg.top_k, libraries=scope,
                                             owner_id=owner_id)
        if cfg.summaries:
            extra = milvus_store.dense_search(mc, SUMMARIES, vector, top_k=cfg.top_k, libraries=scope)
            hits = rrf([hits, best_per_block(extra)], limit=cfg.top_k)
        s.set(hits=len(hits), private_hits=sum(h["library"] == milvus_store.PRIVATE for h in hits))
    if cfg.multihop and llm is not None:
        hits = multihop.expand(u, hits, llm, models, cfg.collection, offered(libraries), scope,
                               mode=cfg.multihop, top_k=cfg.top_k, owner_id=owner_id, mc=mc).hits
    if cfg.rerank_top and hits:
        with spans.span("retrieval", "rerank", n=min(cfg.rerank_top, len(hits))):
            head = hits[:cfg.rerank_top]
            scores = rerank(models, tokenizer, u.standalone_question, [h["text"] for h in head])
            head = [{**h, "score": sc} for sc, h in sorted(zip(scores, head), key=lambda p: -p[0])]
            hits = head + hits[cfg.rerank_top:]
    with spans.span("context", "small_to_big", budget=cfg.budget) as s:
        with DBSession(engine()) as db:
            sources = build_sources(tokenizer, parent_blocks(db, hits, tokenizer), budget=cfg.budget)
        s.set(sources=len(sources), tokens=sum(src.tokens for src in sources))
    return hits, sources


def _search(question: str, history: list[dict] | None, libraries: list[str] | None, cfg: AskConfig,
            llm: LLM, models: ModelServer, on_event: OnEvent, owner_id: int | None = None) -> SearchResult:
    u = understand(llm, question, history, libraries=offered(libraries))
    on_event("understanding", asdict(u))
    if not u.needs_retrieval:
        return SearchResult(u)
    hits, sources = _retrieve(u, libraries, cfg, models, TiktokenTokenizer(), owner_id, llm)
    on_event("sources", {"sources": [source_view(s) for s in sources]})
    retrieved = [{"url": h["url"], "heading_path": h.get("heading_path", ""), "score": round(h["score"], 4)}
                 for h in hits[:10]]
    return SearchResult(u, sources, retrieved)


def search(question: str, history: list[dict] | None = None, libraries: list[str] | None = None,
           cfg: AskConfig | None = None, llm: LLM | None = None, models: ModelServer | None = None,
           on_event: OnEvent = _noop, owner_id: int | None = None, local_llm: LLM | None = None) -> SearchResult:
    """Sources for a question without generating an answer (what a tutor agent quotes from)."""
    with spans.span("request", "search") as root:
        result = _search(question, history, libraries, cfg or AskConfig(), llm or LLM(), models or ModelServer(),
                         on_event, owner_id)
        root.set(sources=len(result.sources))
        result.trace_id = root.trace_id
    return result


def ask(question: str, history: list[dict] | None = None, libraries: list[str] | None = None,
        cfg: AskConfig | None = None, llm: LLM | None = None, models: ModelServer | None = None,
        on_event: OnEvent = _noop, owner_id: int | None = None, local_llm: LLM | None = None) -> AskResult:
    cfg, llm = cfg or AskConfig(), llm or LLM()
    with spans.span("request", "ask", mode=cfg.mode, rerank_top=cfg.rerank_top) as root:
        found = _search(question, history, libraries, cfg, llm, models or ModelServer(), on_event, owner_id)
        private = any(is_private(s) for s in found.sources)
        writer = (local_llm or llm) if private else llm
        result = (answer(writer, found.understanding.standalone_question, found.sources)
                  if found.understanding.needs_retrieval else Answer(False, REFUSAL))
        if cfg.verify and result.found:
            # Same routing as the answer: a private source never leaves the local model.
            result = apply_verification(result, verify(writer, result.text, found.sources))
        root.set(found=result.found, citations=len(result.citations), private_context=private,
                 answer_model=writer.model)
        return AskResult(result, found.understanding, root.trace_id, found.retrieved, found.sources)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("question")
    parser.add_argument("--library", action="append", help="restrict to these libraries (repeatable)")
    parser.add_argument("--mode", choices=("dense", "hybrid"), default="hybrid")
    parser.add_argument("--rerank", type=int, default=0)
    parser.add_argument("--summaries", action="store_true")
    args = parser.parse_args()
    spans.configure(engine())
    r = ask(args.question, libraries=args.library,
            cfg=AskConfig(mode=args.mode, rerank_top=args.rerank, summaries=args.summaries))
    print(json.dumps({"understanding": asdict(r.understanding) if r.understanding else None,
                      "answer": asdict(r.answer), "retrieved": r.retrieved[:5], "trace_id": r.trace_id},
                     ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
